#!/usr/bin/env python3
"""Merge an ESPHome config and its packages into one self-contained YAML file.

The device configs in this repo keep the shared hardware and weather pipeline
in packages/weather-sign-common.yaml and pull it in with `!include`. That is
fine for the CLI, but the ESPHome web app (the Device Builder) wants a single
YAML file that can be pasted in as it is.

This script resolves the package tree with ESPHome's own package merge (the
same one the compiler uses) but stops short of the substitution pass, so the
merged file keeps

  * `!secret <name>` references - the values never leave secrets.yaml, and
  * `${substitution}` references - the `substitutions:` block stays intact.

The result behaves exactly like the original as long as the same secrets are
supplied, which is what the Device Builder's Secrets panel provides.

Usage:
    python scripts/merge_config.py weather-sign.yaml [-o out/weather-sign.yaml]

Without -o the merged YAML goes to stdout.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from esphome import core, yaml_util
from esphome.components.packages import resolve_packages
from esphome.const import __version__ as ESPHOME_VERSION

# The dump renders a secret as `!secret 'name'`; the name is all we want.
SECRET_TAG = re.compile(r"!secret '([^']+)'")


def merge(config_path: Path) -> str:
    """Return the merged YAML for *config_path*."""
    core.CORE.config_path = config_path
    config = yaml_util.load_yaml(config_path)
    return yaml_util.dump(resolve_packages(config))


def header(config_path: Path, merged: str) -> str:
    """Build the comment header that tells the reader what to fill in."""
    secrets = sorted(set(SECRET_TAG.findall(merged)))
    lines = [
        "# " + "-" * 73,
        "# Merged ESPHome configuration - one self-contained file.",
        "#",
        f"# Generated by scripts/merge_config.py from {config_path.name}",
        f"# with ESPHome {ESPHOME_VERSION}. The shared package is inlined,",
        "# so there is nothing left to !include.",
        "#",
        "# Paste this into the ESPHome Device Builder, then add these secrets",
        "# (Device Builder: 3-dot menu -> Secrets):",
    ]
    lines.extend(f"#   {name}" for name in secrets)
    lines.extend(["# " + "-" * 73, ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Merge an ESPHome config into one file.")
    parser.add_argument("config", type=Path, help="device YAML to merge")
    parser.add_argument(
        "-o", "--output", type=Path, help="write the merged YAML here instead of stdout"
    )
    args = parser.parse_args()

    config_path = args.config.resolve()
    if not config_path.is_file():
        parser.error(f"config not found: {config_path}")

    merged = merge(config_path)
    text = header(config_path, merged) + merged

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
